#!/usr/bin/env node
// Builds Field notes from Markdown. Write notes in _notes/your-note-name.md; this script makes:
//   notes/your-note-name.html  one page per published note (from _notes/_layout.html)
//   notes/index.html           every published note, newest first
//   index.html                 the Field notes section between the FIELD NOTES markers (latest 4; hidden when empty)
//   feed.xml                   an Atom feed of every published note
// GitHub Pages skips folders that start with _, so _notes/ is never served (it is still public in the repo).
//   --check  only report files that are out of date (used by CI and the pre-commit hook)
import { readFileSync, writeFileSync, readdirSync, existsSync, unlinkSync, mkdirSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { marked } from 'marked';

const SITE = 'https://alexisdavidson.org';
const HOME_LIMIT = 4;
const GENERATED = 'Generated by scripts/build-notes.mjs. Edit _notes/*.md, not this file.';

process.chdir(execSync('git rev-parse --show-toplevel').toString().trim());
const check = process.argv.includes('--check');
const problems = [];
const writes = new Map(); // path -> contents (null = delete)

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const fill = (tpl, vals) => tpl.replace(/\{\{(\w+)\}\}/g, (_, k) => {
  if (!(k in vals)) throw new Error(`_notes/_layout.html uses {{${k}}}, which the script does not fill`);
  return vals[k];
});
const longDate = (d) => new Date(`${d}T12:00:00Z`).toLocaleDateString('en-US', { timeZone: 'UTC', month: 'long', day: 'numeric', year: 'numeric' });
const shortDate = (d) => new Date(`${d}T12:00:00Z`).toLocaleDateString('en-US', { timeZone: 'UTC', month: 'short', day: 'numeric', year: 'numeric' });

// ---------- Read notes ----------
function parse(file) {
  const raw = readFileSync(`_notes/${file}`, 'utf8').replace(/\r\n/g, '\n');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) { problems.push(`_notes/${file}: missing front matter (the --- block at the top)`); return null; }
  const meta = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (kv) meta[kv[1]] = kv[2].trim().replace(/^(["'])(.*)\1$/, '$2');
  }
  const slug = file.replace(/\.md$/, '');
  const where = `_notes/${file}`;
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug)) problems.push(`${where}: file name must be lowercase words joined by dashes`);
  for (const k of ['title', 'summary', 'label', 'date']) if (!meta[k]) problems.push(`${where}: front matter needs "${k}"`);
  for (const k of ['date', 'updated']) {
    if (meta[k] && (!/^\d{4}-\d{2}-\d{2}$/.test(meta[k]) || isNaN(new Date(meta[k])))) problems.push(`${where}: ${k} must look like 2026-11-12`);
  }
  // House rule: no em dashes, anywhere.
  raw.split('\n').forEach((l, i) => { if (l.includes('\u2014')) problems.push(`${where}:${i + 1}: has an em dash; use a comma, colon, or period instead`); });
  if (/\]\(http:\/\//.test(m[2])) problems.push(`${where}: use https:// links (the site blocks http://)`);
  const words = m[2].split(/\s+/).filter(Boolean).length;
  return { slug, ...meta, draft: meta.draft === 'true', body: m[2], minutes: Math.max(1, Math.round(words / 230)) };
}

mkdirSync('notes', { recursive: true });
const sources = readdirSync('_notes').filter((f) => f.endsWith('.md') && !f.startsWith('_')).sort();
const notes = sources.map(parse).filter((n) => n && !n.draft).sort((a, b) => (b.date + b.slug).localeCompare(a.date + a.slug));
if (problems.length) { console.error(problems.map((p) => `  x ${p}`).join('\n')); process.exit(1); }

const layout = readFileSync('_notes/_layout.html', 'utf8').replace(/<!--\s*FIELD NOTE LAYOUT[\s\S]*?-->\n/, `<!-- ${GENERATED} -->\n`);
for (const k of ['title', 'summary', 'body', 'url']) {
  if (!layout.includes(`{{${k}}}`)) { console.error(`  x _notes/_layout.html: missing {{${k}}}`); process.exit(1); }
}
const metaLine =(n) => [longDate(n.date), `${n.minutes} min read`, n.updated ? `Updated ${longDate(n.updated)}` : null].filter(Boolean).join(' &middot; ');

// ---------- Note pages ----------
for (const n of notes) {
  n.html = marked.parse(n.body, { gfm: true });
  writes.set(`notes/${n.slug}.html`, fill(layout, {
    pageTitle: esc(n.title), title: esc(n.title), summary: esc(n.summary), kicker: esc(n.label),
    url: `${SITE}/notes/${n.slug}.html`, ogType: 'article',
    articleMeta: `<meta property="article:published_time" content="${n.date}">`,
    backHref: './', backLabel: 'All field notes', meta: metaLine(n),
    body: `    <article class="note-body text-ink/90 leading-relaxed">\n${n.html.trim()}\n    </article>`,
  }));
}

// ---------- Cards ----------
const card = (n, href) => `          <article class="note-card soft-card relative p-7 flex flex-col group">
            <div class="flex items-center justify-between gap-3 mb-4">
              <span class="pill">${esc(n.label)}</span>
              <time class="text-sm text-muted" datetime="${n.date}">${shortDate(n.date)}</time>
            </div>
            <h3 class="font-display text-2xl font-bold text-ink mb-3 leading-snug transition-colors group-hover:text-burgundy">
              <a href="${href}" class="after:absolute after:inset-0 after:rounded-[18px] focus:outline-none">${esc(n.title)}</a>
            </h3>
            <p class="text-muted mb-6 flex-1">${esc(n.summary)}</p>
            <span class="text-sm font-medium text-burgundy inline-flex items-center gap-2">Read note <span class="text-muted font-normal">&middot; ${n.minutes} min</span> <span aria-hidden="true" class="transition-transform group-hover:translate-x-1">&rarr;</span></span>
          </article>`;

// ---------- Archive page ----------
if (notes.length) {
  writes.set('notes/index.html', fill(layout, {
    pageTitle: 'Field notes', title: 'Field notes', summary: 'Things I&#39;ve been thinking about.', kicker: 'Writing',
    url: `${SITE}/notes/`, ogType: 'website', articleMeta: '',
    backHref: '../', backLabel: 'Home', meta: `${notes.length} ${notes.length === 1 ? 'note' : 'notes'}`,
    body: `    <div class="grid gap-8">\n${notes.map((n) => card(n, `${n.slug}.html`)).join('\n\n')}\n    </div>`,
  }));
}

// Remove pages this script made earlier whose note was deleted, renamed, or turned back into a draft.
for (const f of readdirSync('notes').filter((f) => f.endsWith('.html'))) {
  const p = `notes/${f}`;
  if (!writes.has(p) && readFileSync(p, 'utf8').includes(GENERATED)) writes.set(p, null);
}

// ---------- Homepage section ----------
const START = '<!-- FIELD NOTES:START', END = '<!-- FIELD NOTES:END -->';
const home = readFileSync('index.html', 'utf8');
const a = home.indexOf(START), b = home.indexOf(END);
if (a < 0 || b < 0) { console.error('  x index.html: missing the FIELD NOTES:START / FIELD NOTES:END markers'); process.exit(1); }
const startLine = home.slice(a, home.indexOf('-->', a) + 3);
const latest = notes.slice(0, HOME_LIMIT);
const section = !notes.length ? '' : `
    <section id="field-notes">
      <div class="max-w-5xl mx-auto px-6 py-20 md:py-28">
        <h2 class="section-title mb-4">Field notes</h2>
        <p class="text-muted text-lg mb-12">Things I've been thinking about</p>
        <div class="grid md:grid-cols-2 gap-8">
${latest.map((n) => card(n, `notes/${n.slug}.html`)).join('\n\n')}
        </div>
        <p class="mt-10 flex flex-wrap gap-x-6 gap-y-2 text-base font-medium">
          ${notes.length > HOME_LIMIT ? `<a href="notes/" class="text-burgundy link-underline">All ${notes.length} notes &rarr;</a>` : ''}
          <a href="feed.xml" class="text-muted link-underline">Follow by feed</a>
        </p>
      </div>
    </section>
    `;
writes.set('index.html', home.slice(0, a) + startLine + section.replace(/\n {10}\n/, '\n') + home.slice(b));

// ---------- Feed ----------
const newest = notes.length ? notes.map((n) => n.updated || n.date).sort().at(-1) : '2026-01-01';
writes.set('feed.xml', `<?xml version="1.0" encoding="utf-8"?>
<feed xmlns="http://www.w3.org/2005/Atom">
  <title>Alexis Davidson: Field notes</title>
  <subtitle>Things I've been thinking about</subtitle>
  <link href="${SITE}/feed.xml" rel="self"/>
  <link href="${SITE}/"/>
  <id>${SITE}/</id>
  <updated>${newest}T12:00:00Z</updated>
  <author><name>Alexis Davidson</name></author>
${notes.map((n) => `  <entry>
    <title>${esc(n.title)}</title>
    <link href="${SITE}/notes/${n.slug}.html"/>
    <id>${SITE}/notes/${n.slug}.html</id>
    <published>${n.date}T12:00:00Z</published>
    <updated>${n.updated || n.date}T12:00:00Z</updated>
    <category term="${esc(n.label)}"/>
    <summary>${esc(n.summary)}</summary>
    <content type="html">${esc(n.html)}</content>
  </entry>`).join('\n')}
</feed>
`);

// ---------- Write or check ----------
// Asset stamps (?v=...) are added later by stamp-assets.sh, so they're ignored when comparing.
const unstamp = (s) => s.replace(/\?v=[0-9a-f]+"/g, '"');
let stale = 0;
for (const [p, want] of writes) {
  const have = existsSync(p) ? readFileSync(p, 'utf8') : null;
  if (want === null) {
    if (check) { console.log(`${p}: no longer has a note; rebuild to remove it`); stale = 1; }
    else { unlinkSync(p); console.log(`Removed ${p}`); }
  } else if (have === null || unstamp(have) !== unstamp(want)) {
    if (check) { console.log(`${p}: out of date`); stale = 1; }
    else { writeFileSync(p, want); console.log(`Wrote ${p}`); }
  }
}
if (check && stale) { console.log('Run npm run build and commit the result.'); process.exit(1); }
if (!check) console.log(`${notes.length} published ${notes.length === 1 ? 'note' : 'notes'}, ${sources.length - notes.length} draft or invalid`);
